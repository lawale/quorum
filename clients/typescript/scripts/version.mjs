// Writes src/version.ts from package.json so the built client reports the
// version it was published as. The release workflow sets package.json's
// version from the git tag before building, so this is the release version;
// a checkout reports 0.0.0.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const out = `// Generated by scripts/version.mjs from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(version)};\n`;
const target = join(root, "src", "version.ts");
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {}
if (current !== out) writeFileSync(target, out);
